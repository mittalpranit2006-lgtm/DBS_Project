-- Creates one dedicated local PDB user. Review 00_admin_preflight.sql first.
-- Run ONLY from a fresh SYSTEM connection to XEPDB1; never in CDB$ROOT.
-- Do not SPOOL this script. ACCEPT HIDE, ECHO OFF and VERIFY OFF protect input display.
SET ECHO OFF
SET VERIFY OFF
SET SERVEROUTPUT ON
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

-- Repeat preflight inline so a missing include cannot bypass safety checks.
DECLARE
  v_count NUMBER;
  v_free_bytes NUMBER;
  v_growth_bytes NUMBER;
BEGIN
  IF USER <> 'SYSTEM' OR SYS_CONTEXT('USERENV', 'CON_NAME') <> 'XEPDB1' THEN
    RAISE_APPLICATION_ERROR(-20001, 'Expected SYSTEM connected to XEPDB1; no changes made');
  END IF;
  SELECT COUNT(*) INTO v_count FROM DBA_TABLESPACES
   WHERE TABLESPACE_NAME = 'USERS' AND CONTENTS = 'PERMANENT' AND STATUS = 'ONLINE';
  IF v_count <> 1 THEN RAISE_APPLICATION_ERROR(-20002, 'USERS tablespace not online'); END IF;
  SELECT COUNT(*) INTO v_count FROM DBA_TABLESPACES
   WHERE TABLESPACE_NAME = 'TEMP' AND CONTENTS = 'TEMPORARY' AND STATUS = 'ONLINE';
  IF v_count <> 1 THEN RAISE_APPLICATION_ERROR(-20003, 'TEMP tablespace not online'); END IF;
  SELECT NVL(SUM(bytes),0) INTO v_free_bytes FROM DBA_FREE_SPACE
   WHERE TABLESPACE_NAME = 'USERS';
  SELECT NVL(SUM(CASE WHEN AUTOEXTENSIBLE = 'YES'
                      THEN GREATEST(MAXBYTES - BYTES,0) ELSE 0 END),0)
    INTO v_growth_bytes FROM DBA_DATA_FILES WHERE TABLESPACE_NAME = 'USERS';
  IF v_free_bytes + v_growth_bytes < 20 * 1024 * 1024 THEN
    RAISE_APPLICATION_ERROR(-20005, 'USERS has less than 20 MB free/autoextend headroom');
  END IF;
  SELECT COUNT(*) INTO v_count FROM DBA_USERS WHERE USERNAME = 'SVR_APP';
  IF v_count <> 0 THEN RAISE_APPLICATION_ERROR(-20004, 'SVR_APP already exists'); END IF;
  DBMS_OUTPUT.PUT_LINE('PASS: SYSTEM / XEPDB1; USERS and TEMP online; USERS headroom >= 20 MB; SVR_APP absent.');
END;
/

SET DEFINE ON
ACCEPT svr_password CHAR PROMPT 'New SVR_APP password (hidden input; avoid quotes and ampersands): ' HIDE
CREATE USER SVR_APP IDENTIFIED BY "&&svr_password"
  DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP
  QUOTA 20M ON USERS;
UNDEFINE svr_password
CLEAR BUFFER

GRANT CREATE SESSION, CREATE TABLE TO SVR_APP;

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM DBA_USERS
   WHERE USERNAME='SVR_APP' AND DEFAULT_TABLESPACE='USERS' AND TEMPORARY_TABLESPACE='TEMP';
  IF v_count <> 1 THEN RAISE_APPLICATION_ERROR(-20006,'SVR_APP post-creation account check failed'); END IF;
  SELECT COUNT(*) INTO v_count FROM DBA_TS_QUOTAS
   WHERE USERNAME='SVR_APP' AND TABLESPACE_NAME='USERS' AND MAX_BYTES=20*1024*1024;
  IF v_count <> 1 THEN RAISE_APPLICATION_ERROR(-20007,'SVR_APP 20 MB quota check failed'); END IF;
  SELECT COUNT(*) INTO v_count FROM DBA_SYS_PRIVS
   WHERE GRANTEE='SVR_APP' AND PRIVILEGE IN ('CREATE SESSION','CREATE TABLE');
  IF v_count <> 2 THEN RAISE_APPLICATION_ERROR(-20008,'SVR_APP privilege check failed'); END IF;
  DBMS_OUTPUT.PUT_LINE('PASS SVR_APP created in XEPDB1 with CREATE SESSION, CREATE TABLE and 20 MB USERS quota.');
END;
/
