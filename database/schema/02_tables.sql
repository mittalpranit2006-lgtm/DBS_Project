-- One-time eight-table schema. DDL commits implicitly; no automatic DROP or reset.
SET ECHO OFF
SET VERIFY OFF
SET SERVEROUTPUT ON
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
BEGIN
  IF USER <> 'SVR_APP' OR SYS_CONTEXT('USERENV', 'CON_NAME') <> 'XEPDB1' THEN
    RAISE_APPLICATION_ERROR(-20010, 'Expected SVR_APP in XEPDB1; no DDL run');
  END IF;
END;
/
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TABLES;
  IF v_count <> 0 THEN
    RAISE_APPLICATION_ERROR(-20011, 'Account already has tables; inspect before any schema rerun');
  END IF;
END;
/

CREATE TABLE CUSTOMER (
  Customer_ID NUMBER(6) CONSTRAINT PK_CUSTOMER PRIMARY KEY,
  First_Name VARCHAR2(60 CHAR) NOT NULL,
  Last_Name VARCHAR2(60 CHAR) NOT NULL,
  Email VARCHAR2(254 CHAR) NOT NULL,
  License_No VARCHAR2(24 CHAR) NOT NULL,
  Address VARCHAR2(240 CHAR) NOT NULL,
  Registration_Date DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT UQ_CUSTOMER_EMAIL UNIQUE (Email),
  CONSTRAINT UQ_CUSTOMER_LICENSE UNIQUE (License_No)
);

CREATE TABLE CUSTOMER_PHONE (
  Customer_ID NUMBER(6) NOT NULL,
  Phone_No VARCHAR2(15 CHAR) NOT NULL,
  CONSTRAINT PK_CUSTOMER_PHONE PRIMARY KEY (Customer_ID, Phone_No),
  CONSTRAINT FK_CPHONE_CUSTOMER FOREIGN KEY (Customer_ID) REFERENCES CUSTOMER(Customer_ID),
  CONSTRAINT CK_CPHONE_DIGITS CHECK (REGEXP_LIKE(Phone_No, '^[0-9]{10,15}$'))
);

CREATE TABLE VEHICLE_TYPE (
  Type_ID NUMBER(4) CONSTRAINT PK_VEHICLE_TYPE PRIMARY KEY,
  Type_Name VARCHAR2(60 CHAR) NOT NULL,
  Daily_Rate NUMBER(10,2) NOT NULL,
  Security_Deposit NUMBER(10,2) DEFAULT 0 NOT NULL,
  CONSTRAINT UQ_VTYPE_NAME UNIQUE (Type_Name),
  CONSTRAINT CK_VTYPE_RATE CHECK (Daily_Rate > 0),
  CONSTRAINT CK_VTYPE_DEPOSIT CHECK (Security_Deposit >= 0)
);

CREATE TABLE BRANCH (
  Branch_ID NUMBER(4) CONSTRAINT PK_BRANCH PRIMARY KEY,
  Branch_Name VARCHAR2(80 CHAR) NOT NULL,
  Location VARCHAR2(160 CHAR) NOT NULL,
  Phone VARCHAR2(15 CHAR) NOT NULL,
  CONSTRAINT UQ_BRANCH_NAME_LOC UNIQUE (Branch_Name, Location),
  CONSTRAINT UQ_BRANCH_PHONE UNIQUE (Phone),
  CONSTRAINT CK_BRANCH_PHONE CHECK (REGEXP_LIKE(Phone, '^[0-9]{10,15}$'))
);

CREATE TABLE VEHICLE (
  Vehicle_ID NUMBER(6) CONSTRAINT PK_VEHICLE PRIMARY KEY,
  Registration_No VARCHAR2(24 CHAR) NOT NULL,
  Brand VARCHAR2(60 CHAR) NOT NULL,
  Model VARCHAR2(60 CHAR) NOT NULL,
  Purchase_Year NUMBER(4) NOT NULL,
  Availability_Status VARCHAR2(16 CHAR) DEFAULT 'Available' NOT NULL,
  Type_ID NUMBER(4) NOT NULL,
  Branch_ID NUMBER(4) NOT NULL,
  CONSTRAINT UQ_VEHICLE_REG UNIQUE (Registration_No),
  CONSTRAINT CK_VEHICLE_YEAR CHECK (Purchase_Year BETWEEN 1990 AND 2100),
  CONSTRAINT CK_VEHICLE_AVAIL CHECK (Availability_Status IN ('Available','Rented','Maintenance')),
  CONSTRAINT FK_VEHICLE_TYPE FOREIGN KEY (Type_ID) REFERENCES VEHICLE_TYPE(Type_ID),
  CONSTRAINT FK_VEHICLE_BRANCH FOREIGN KEY (Branch_ID) REFERENCES BRANCH(Branch_ID)
);

CREATE TABLE EMPLOYEE (
  Employee_ID NUMBER(6) CONSTRAINT PK_EMPLOYEE PRIMARY KEY,
  Name VARCHAR2(120 CHAR) NOT NULL,
  Email VARCHAR2(254 CHAR) NOT NULL,
  Phone VARCHAR2(15 CHAR) NOT NULL,
  "ROLE" VARCHAR2(40 CHAR) NOT NULL,
  Branch_ID NUMBER(4) NOT NULL,
  CONSTRAINT UQ_EMPLOYEE_EMAIL UNIQUE (Email),
  CONSTRAINT UQ_EMPLOYEE_PHONE UNIQUE (Phone),
  CONSTRAINT CK_EMPLOYEE_PHONE CHECK (REGEXP_LIKE(Phone, '^[0-9]{10,15}$')),
  CONSTRAINT FK_EMPLOYEE_BRANCH FOREIGN KEY (Branch_ID) REFERENCES BRANCH(Branch_ID)
);

CREATE TABLE RENTAL (
  Rental_ID NUMBER(8) CONSTRAINT PK_RENTAL PRIMARY KEY,
  Customer_ID NUMBER(6) NOT NULL,
  Vehicle_ID NUMBER(6) NOT NULL,
  Employee_ID NUMBER(6) NOT NULL,
  Status_Name VARCHAR2(12 CHAR) DEFAULT 'Active' NOT NULL,
  Start_Date TIMESTAMP(0) NOT NULL,
  Expected_Return_Date TIMESTAMP(0) NOT NULL,
  Actual_Return_Date TIMESTAMP(0),
  Total_Amount NUMBER(12,2) DEFAULT 0 NOT NULL,
  Daily_Rate_Snapshot NUMBER(10,2) NOT NULL,
  CONSTRAINT FK_RENTAL_CUSTOMER FOREIGN KEY (Customer_ID) REFERENCES CUSTOMER(Customer_ID),
  CONSTRAINT FK_RENTAL_VEHICLE FOREIGN KEY (Vehicle_ID) REFERENCES VEHICLE(Vehicle_ID),
  CONSTRAINT FK_RENTAL_EMPLOYEE FOREIGN KEY (Employee_ID) REFERENCES EMPLOYEE(Employee_ID),
  CONSTRAINT CK_RENTAL_STATUS CHECK (Status_Name IN ('Active','Completed','Cancelled')),
  CONSTRAINT CK_RENTAL_DATES CHECK (Expected_Return_Date > Start_Date
    AND (Actual_Return_Date IS NULL OR Actual_Return_Date >= Start_Date)),
  CONSTRAINT CK_RENTAL_RETURN_STATE CHECK (
    (Status_Name = 'Completed' AND Actual_Return_Date IS NOT NULL) OR
    (Status_Name IN ('Active','Cancelled') AND Actual_Return_Date IS NULL)),
  CONSTRAINT CK_RENTAL_AMOUNT CHECK (Total_Amount >= 0 AND
    (Status_Name <> 'Cancelled' OR Total_Amount = 0)),
  CONSTRAINT CK_RENTAL_RATE CHECK (Daily_Rate_Snapshot > 0)
);

-- At most one currently Active rental per vehicle. Historical overlap and
-- availability synchronization still need transactional Step 3 logic.
CREATE UNIQUE INDEX UQ_RENTAL_ACTIVE_VEH ON RENTAL
  (CASE WHEN Status_Name = 'Active' THEN Vehicle_ID END);

CREATE TABLE PAYMENT (
  Payment_ID NUMBER(8) CONSTRAINT PK_PAYMENT PRIMARY KEY,
  Rental_ID NUMBER(8) NOT NULL,
  Payment_Date TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
  Amount NUMBER(12,2) NOT NULL,
  Payment_Method VARCHAR2(20 CHAR) NOT NULL,
  Payment_Status VARCHAR2(12 CHAR) DEFAULT 'Completed' NOT NULL,
  CONSTRAINT FK_PAYMENT_RENTAL FOREIGN KEY (Rental_ID) REFERENCES RENTAL(Rental_ID),
  CONSTRAINT CK_PAYMENT_AMOUNT CHECK (Amount > 0),
  CONSTRAINT CK_PAYMENT_METHOD CHECK (Payment_Method IN ('Card','UPI','Cash','Bank Transfer')),
  CONSTRAINT CK_PAYMENT_STATUS CHECK (Payment_Status IN ('Pending','Completed','Refunded'))
);

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TABLES;
  IF v_count <> 8 THEN RAISE_APPLICATION_ERROR(-20012,'Eight-table schema post-check failed'); END IF;
  SELECT COUNT(*) INTO v_count FROM USER_INDEXES
   WHERE INDEX_NAME='UQ_RENTAL_ACTIVE_VEH' AND STATUS='VALID' AND UNIQUENESS='UNIQUE';
  IF v_count <> 1 THEN RAISE_APPLICATION_ERROR(-20013,'Active-vehicle index post-check failed'); END IF;
  DBMS_OUTPUT.PUT_LINE('PASS eight project tables and active-rental unique index created.');
END;
