-- Final read-only count/cleanup check after the last browser update test.
SET ECHO OFF VERIFY OFF
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CONNECT / AS SYSDBA
ALTER SESSION SET CONTAINER = XEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = SVR_APP;
SPOOL evidence/step6a-post-cleanup-sys.log
SELECT USER AS audit_account, SYS_CONTEXT('USERENV','CON_NAME') AS container_name,
 SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AS compared_schema FROM dual;
SELECT 'CUSTOMER' AS table_name,COUNT(*) AS row_count FROM CUSTOMER
UNION ALL SELECT 'CUSTOMER_PHONE',COUNT(*) FROM CUSTOMER_PHONE
UNION ALL SELECT 'VEHICLE_TYPE',COUNT(*) FROM VEHICLE_TYPE
UNION ALL SELECT 'BRANCH',COUNT(*) FROM BRANCH
UNION ALL SELECT 'VEHICLE',COUNT(*) FROM VEHICLE
UNION ALL SELECT 'EMPLOYEE',COUNT(*) FROM EMPLOYEE
UNION ALL SELECT 'RENTAL',COUNT(*) FROM RENTAL
UNION ALL SELECT 'PAYMENT',COUNT(*) FROM PAYMENT;
SELECT 'TEST CUSTOMERS' AS label,COUNT(*) AS leftovers FROM CUSTOMER WHERE CUSTOMER_ID IN (1986,1987,1989,1990)
UNION ALL SELECT 'TEST TYPES',COUNT(*) FROM VEHICLE_TYPE WHERE TYPE_ID=98
UNION ALL SELECT 'TEST BRANCHES',COUNT(*) FROM BRANCH WHERE BRANCH_ID=98
UNION ALL SELECT 'TEST VEHICLES',COUNT(*) FROM VEHICLE WHERE VEHICLE_ID=3986
UNION ALL SELECT 'TEST EMPLOYEES',COUNT(*) FROM EMPLOYEE WHERE EMPLOYEE_ID=2986
UNION ALL SELECT 'TEST RENTALS',COUNT(*) FROM RENTAL WHERE RENTAL_ID>=7000
UNION ALL SELECT 'TEST PAYMENTS',COUNT(*) FROM PAYMENT WHERE PAYMENT_ID>=8000;
SELECT COUNT(*) AS invalid_svr_objects FROM DBA_OBJECTS WHERE OWNER='SVR_APP' AND STATUS<>'VALID';
SELECT COUNT(*) AS svr_compilation_errors FROM DBA_ERRORS WHERE OWNER='SVR_APP';
SELECT CONSTRAINT_TYPE,STATUS,VALIDATED,COUNT(*) AS constraint_count
 FROM DBA_CONSTRAINTS WHERE OWNER='SVR_APP' AND TABLE_NAME IN
 ('CUSTOMER','CUSTOMER_PHONE','VEHICLE_TYPE','BRANCH','VEHICLE','EMPLOYEE','RENTAL','PAYMENT')
 GROUP BY CONSTRAINT_TYPE,STATUS,VALIDATED ORDER BY CONSTRAINT_TYPE;
SPOOL OFF
EXIT SUCCESS
