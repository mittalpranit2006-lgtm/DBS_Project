-- Fresh, read-only database check immediately after normal browser rental start.
SET ECHO OFF VERIFY OFF
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CONNECT / AS SYSDBA
ALTER SESSION SET CONTAINER = XEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = SVR_APP;
SPOOL evidence/step6a-committed-after-start.log
SELECT USER AS audit_account,SYS_CONTEXT('USERENV','CON_NAME') AS container_name,
 SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AS project_schema FROM dual;
SELECT r.RENTAL_ID,r.CUSTOMER_ID,r.VEHICLE_ID,r.EMPLOYEE_ID,r.STATUS_NAME,
 TO_CHAR(r.START_DATE,'YYYY-MM-DD HH24:MI:SS') AS start_date,
 TO_CHAR(r.EXPECTED_RETURN_DATE,'YYYY-MM-DD HH24:MI:SS') AS expected_return_date,
 TO_CHAR(r.ACTUAL_RETURN_DATE,'YYYY-MM-DD HH24:MI:SS') AS actual_return_date,
 r.TOTAL_AMOUNT,r.DAILY_RATE_SNAPSHOT,v.AVAILABILITY_STATUS,t.DAILY_RATE AS type_rate
 FROM RENTAL r JOIN VEHICLE v ON v.VEHICLE_ID=r.VEHICLE_ID
 JOIN VEHICLE_TYPE t ON t.TYPE_ID=v.TYPE_ID
 WHERE r.RENTAL_ID=7016 AND r.CUSTOMER_ID=1981 AND r.VEHICLE_ID=3981;
SELECT COUNT(*) AS matching_test_rentals FROM RENTAL
 WHERE CUSTOMER_ID=1981 AND VEHICLE_ID=3981;
SELECT COUNT(*) AS matching_test_payments FROM PAYMENT WHERE RENTAL_ID=7016;
SPOOL OFF
EXIT SUCCESS
