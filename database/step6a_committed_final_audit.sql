  SELECT COUNT(*) INTO n FROM DBA_ERRORS WHERE OWNER='SVR_APP'; zero('compilation errors');
  SELECT COUNT(*) INTO n FROM CUSTOMER_PHONE cp WHERE NOT EXISTS
   (SELECT 1 FROM CUSTOMER c WHERE c.CUSTOMER_ID=cp.CUSTOMER_ID); zero('orphan customer phones');
  SELECT COUNT(*) INTO n FROM VEHICLE v WHERE NOT EXISTS
