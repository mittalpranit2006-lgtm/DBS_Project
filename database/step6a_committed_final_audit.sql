DECLARE
  n NUMBER;
  PROCEDURE zero(p_label VARCHAR2) IS BEGIN
    IF n <> 0 THEN RAISE_APPLICATION_ERROR(-20610,p_label||' count='||n); END IF;
    DBMS_OUTPUT.PUT_LINE('PASS '||p_label||' = 0');
