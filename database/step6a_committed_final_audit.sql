   (SELECT 1 FROM BRANCH b WHERE b.BRANCH_ID=v.BRANCH_ID); zero('orphan vehicle references');
  SELECT COUNT(*) INTO n FROM EMPLOYEE e WHERE NOT EXISTS
   (SELECT 1 FROM BRANCH b WHERE b.BRANCH_ID=e.BRANCH_ID); zero('orphan employees');
  SELECT COUNT(*) INTO n FROM RENTAL r WHERE NOT EXISTS
   (SELECT 1 FROM CUSTOMER c WHERE c.CUSTOMER_ID=r.CUSTOMER_ID) OR NOT EXISTS
   (SELECT 1 FROM VEHICLE v WHERE v.VEHICLE_ID=r.VEHICLE_ID) OR NOT EXISTS
   (SELECT 1 FROM EMPLOYEE e WHERE e.EMPLOYEE_ID=r.EMPLOYEE_ID); zero('orphan rentals');
  SELECT COUNT(*) INTO n FROM PAYMENT p WHERE NOT EXISTS
   (SELECT 1 FROM RENTAL r WHERE r.RENTAL_ID=p.RENTAL_ID); zero('orphan payments');
  SELECT COUNT(*) INTO n FROM VEHICLE v WHERE
   (v.AVAILABILITY_STATUS='Rented' AND NOT EXISTS
    (SELECT 1 FROM RENTAL r WHERE r.VEHICLE_ID=v.VEHICLE_ID AND r.STATUS_NAME='Active'))
