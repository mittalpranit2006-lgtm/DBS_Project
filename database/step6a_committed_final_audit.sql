    GREATEST(1,CEIL(CAST(r.ACTUAL_RETURN_DATE AS DATE)-CAST(r.START_DATE AS DATE)))*r.DAILY_RATE_SNAPSHOT)
   OR (r.STATUS_NAME='Cancelled' AND r.TOTAL_AMOUNT<>0);
