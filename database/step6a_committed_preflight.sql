-- Read-only preflight for the committed browser workflow follow-up.
SET ECHO OFF VERIFY OFF
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CONNECT / AS SYSDBA
ALTER SESSION SET CONTAINER = XEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = SVR_APP;
SPOOL evidence/step6a-committed-preflight.log
SELECT USER AS audit_account, SYS_CONTEXT('USERENV','CON_NAME') AS container_name,
  SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AS project_schema FROM dual;
SELECT 'CUSTOMER' AS table_name, COUNT(*) AS row_count FROM CUSTOMER
UNION ALL SELECT 'CUSTOMER_PHONE',COUNT(*) FROM CUSTOMER_PHONE
UNION ALL SELECT 'VEHICLE_TYPE',COUNT(*) FROM VEHICLE_TYPE
UNION ALL SELECT 'BRANCH',COUNT(*) FROM BRANCH
UNION ALL SELECT 'VEHICLE',COUNT(*) FROM VEHICLE
UNION ALL SELECT 'EMPLOYEE',COUNT(*) FROM EMPLOYEE
UNION ALL SELECT 'RENTAL',COUNT(*) FROM RENTAL
UNION ALL SELECT 'PAYMENT',COUNT(*) FROM PAYMENT;
SELECT 'CUSTOMER 1981' AS candidate,COUNT(*) AS existing_rows FROM CUSTOMER WHERE CUSTOMER_ID=1981
UNION ALL SELECT 'VEHICLE 3981',COUNT(*) FROM VEHICLE WHERE VEHICLE_ID=3981;
SELECT t.TYPE_ID,t.TYPE_NAME,t.DAILY_RATE,b.BRANCH_ID,b.BRANCH_NAME,
 e.EMPLOYEE_ID,e.NAME AS employee_name,e.BRANCH_ID AS employee_branch_id
 FROM VEHICLE_TYPE t CROSS JOIN BRANCH b JOIN EMPLOYEE e ON e.BRANCH_ID=b.BRANCH_ID
 WHERE t.TYPE_ID=1 AND b.BRANCH_ID=1 AND e.EMPLOYEE_ID=2001;
SPOOL OFF
EXIT SUCCESS
