SET ECHO OFF VERIFY OFF
CONNECT SVR_APP@"DESKTOP-FFIRV71:1521/xepdb1"
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SPOOL evidence/step3-install.log
SHOW USER
SELECT SYS_CONTEXT('USERENV','CON_NAME') AS CONTAINER_NAME FROM DUAL;
@database/step3/01_objects.sql
SELECT OBJECT_NAME,OBJECT_TYPE,STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('SVR_WORKFLOW','TRG_SVR_RENTAL','TRG_SVR_PAYMENT','SEQ_SVR_RENTAL','SEQ_SVR_PAYMENT')
 ORDER BY OBJECT_NAME,OBJECT_TYPE;
SELECT NAME,TYPE,LINE,POSITION,TEXT FROM USER_ERRORS
 WHERE NAME IN ('SVR_WORKFLOW','TRG_SVR_RENTAL','TRG_SVR_PAYMENT') ORDER BY NAME,SEQUENCE;
SPOOL OFF
EXIT
